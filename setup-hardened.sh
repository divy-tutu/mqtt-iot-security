#!/usr/bin/env bash
# One-time provisioning for the Phase-2 HARDENED stack.
#
# Generates the trust material that is git-ignored (so private keys never land
# in version control) but that the hardened broker and devices need to run:
#
#   broker/certs/   TLS CA + broker server certificate
#   secrets/        per-device + operator HMAC keys
#   broker/config/passwd   hashed credentials (via mosquitto_passwd)
#
# The per-topic ACL (broker/config/acl) and all configs are committed, so this
# script only produces secrets. Safe to re-run; existing HMAC keys are kept.
#
# After this, bring the stack up with:
#   docker compose -f docker-compose.hardened.yml up -d --build
set -euo pipefail
cd "$(dirname "$0")"
export MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL="*"

# Credentials MUST match the device environment in docker-compose.hardened.yml.
declare -A CREDS=(
  [sensor-livingroom]=sensor-pass-2026
  [lock-frontdoor]=lock-pass-2026
  [camera-frontdoor]=camera-pass-2026
  [dashboard]=dashboard-pass-2026
)

echo "==> 1/3 TLS certificates"
bash broker/certs/gen-certs.sh

echo "==> 2/3 per-device HMAC keys (secrets/)"
mkdir -p secrets
for id in sensor-livingroom lock-frontdoor camera-frontdoor dashboard; do
  f="secrets/${id}.hmac.key"
  if [ -s "$f" ]; then
    echo "    keep $f"
  else
    openssl rand -hex 32 > "$f"
    echo "    new  $f"
  fi
done

echo "==> 3/3 hashed password file (broker/config/passwd)"
first=1
for user in "${!CREDS[@]}"; do
  if [ "$first" = 1 ]; then flag="-c"; first=0; else flag=""; fi
  docker run --rm -v "$(pwd)/broker/config:/work" eclipse-mosquitto:2 \
    mosquitto_passwd -b $flag /work/passwd "$user" "${CREDS[$user]}"
done

echo "==> 4/4 frontend secure-build env (frontend/.env.local)"
cat > frontend/.env.local <<EOF
# Auto-generated by setup-hardened.sh. GIT-IGNORED. Testbed-only: embeds broker
# credentials + HMAC keys in the browser build (see frontend/.env.example).
VITE_MQTT_WSS_URL=wss://localhost:9002
VITE_MQTT_USERNAME=dashboard
VITE_MQTT_PASSWORD=${CREDS[dashboard]}
VITE_HMAC_SENSOR=$(cat secrets/sensor-livingroom.hmac.key)
VITE_HMAC_LOCK=$(cat secrets/lock-frontdoor.hmac.key)
VITE_HMAC_CAMERA=$(cat secrets/camera-frontdoor.hmac.key)
VITE_HMAC_OPERATOR=$(cat secrets/dashboard.hmac.key)
EOF
echo "    wrote frontend/.env.local"

echo
echo "Done. Start the hardened stack:"
echo "  docker compose -f docker-compose.hardened.yml up -d --build"
echo
echo "For the SECURE frontend build (wss), trust the testbed CA once, then run vite:"
echo "  certutil -addstore -user Root broker/certs/ca.crt   # Windows (per-user)"
echo "  (cd frontend && npm run dev)   # then open http://localhost:8080 and pick Secure mode"
